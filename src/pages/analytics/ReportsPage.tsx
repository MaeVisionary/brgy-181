import { Download, FileClock, FileSpreadsheet, FileText, Lock } from 'lucide-react'
import { useEffect, useMemo, useState } from 'react'
import { Link } from 'react-router-dom'
import { useAuth } from '@/auth/useAuth'
import { useAnalytics } from '@/analytics/AnalyticsContext'
import { FILTER_LABELS, applyFilters, deriveRows, type Filters } from '@/analytics/compute'
import { exportExcel, exportPdf, type ReportOutput } from '@/analytics/exporters'
import { SENIOR_REPORTS } from '@/analytics/reports'
import { Badge } from '@/components/ui/Badge'
import { Button } from '@/components/ui/Button'
import { PageHeader } from '@/components/ui/PageHeader'
import { Card, Panel } from '@/components/ui/Panel'
import { BARANGAY, RECURRING_REPORTS, REPORT_CATEGORIES } from '@/config/barangay'
import { cn } from '@/lib/cn'
import { audit } from '@/services/auditService'

export function ReportsPage() {
  const { user, can } = useAuth()
  const { dataset, reportingDate, filters } = useAnalytics()
  const [reportId, setReportId] = useState(SENIOR_REPORTS[1].id)
  const [useFilters, setUseFilters] = useState(false)
  const showPii = can('residents.view')
  const canExport = can('reports.export')
  const def = SENIOR_REPORTS.find((r) => r.id === reportId)!
  const locked = def.pii && !showPii

  const output = useMemo<ReportOutput | null>(() => {
    if (!dataset || locked) return null
    const rows = applyFilters(deriveRows(dataset, reportingDate), useFilters ? filters : ({} as Filters), { searchNames: showPii })
    const built = def.build(rows, { showPii })
    const active = Object.entries(useFilters ? filters : {}).filter(([, v]) => v)
    return {
      title: def.name,
      meta: [
        ['Barangay', BARANGAY.fullName],
        ['Source dataset', dataset.fileName],
        ['Reporting date', reportingDate.toISOString().slice(0, 10)],
        ['Date generated', new Date().toLocaleString('en-PH')],
        ['Generated by', `${user?.fullName ?? ''} (${user?.position ?? ''})`],
        ['Filters', active.map(([k, v]) => `${FILTER_LABELS[k as keyof Filters]}: ${v}`).join('; ') || 'None (all records)'],
      ],
      ...built,
    }
  }, [dataset, reportingDate, filters, useFilters, def, locked, showPii, user])

  useEffect(() => {
    if (output && user) audit(user, `Generated report: ${def.name}`, 'Reports')
    // log once per report selection, not on every render
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [reportId, dataset])

  const doExport = async (kind: 'pdf' | 'xlsx') => {
    if (!output || !user) return
    audit(user, `Exported ${kind.toUpperCase()}: ${def.name}`, 'Reports', def.pii ? 'contains identifiable information' : undefined)
    if (kind === 'pdf') exportPdf(output)
    else await exportExcel(output)
  }

  return (
    <>
      <PageHeader title="Barangay Reports" subtitle="Recurring reports for government offices and internal analytics reports." />

      <Panel title="Official reports" subtitle="Recipients identified in the workflows document and the study. Formats will follow the files the barangay provides.">
        <div className="grid gap-3 md:grid-cols-2 xl:grid-cols-4">
          {REPORT_CATEGORIES.map((c) => (
            <div key={c.id} className="rounded-[var(--radius-control)] border border-line px-4 py-3">
              <p className="font-display text-[15px] font-extrabold text-navy-900">{c.name}</p>
              <p className="text-[12px] text-ink-muted">{c.full}</p>
              <p className="mt-2"><Badge tone="neutral">Template pending</Badge></p>
            </div>
          ))}
        </div>
        <ul className="mt-4 divide-y divide-line-soft rounded-[var(--radius-control)] border border-line">
          {RECURRING_REPORTS.map((r) => (
            <li key={r.id} className="flex items-center justify-between gap-3 px-4 py-3">
              <span className="flex items-center gap-2.5">
                <FileClock className="size-4 text-ink-muted" />
                <span>
                  <span className="block text-[13px] font-semibold text-navy-900">{r.name}</span>
                  <span className="block text-[11.5px] text-ink-muted">{r.schedule}</span>
                </span>
              </span>
              <span className="text-right text-[11.5px] text-ink-muted">
                {r.id === 'senior-masterlist' ? 'Official OSCA format pending. Use the internal masterlist report below meanwhile.' : 'Waiting for the official template'}
              </span>
            </li>
          ))}
        </ul>
      </Panel>

      <div className="mt-4 grid gap-4 xl:grid-cols-[300px_minmax(0,1fr)]">
        <Card className="h-fit overflow-hidden">
          <p className="label-caps border-b border-line-soft px-4 py-3">Internal analytics reports</p>
          <ul>
            {SENIOR_REPORTS.map((r) => (
              <li key={r.id} className="border-b border-line-soft last:border-0">
                <button type="button" onClick={() => setReportId(r.id)} className={cn('flex w-full items-start gap-2.5 px-4 py-3 text-left', r.id === reportId ? 'bg-sky-100' : 'hover:bg-sky-50')}>
                  <FileText className="mt-0.5 size-4 shrink-0 text-navy-900" />
                  <span className="min-w-0 flex-1">
                    <span className="block text-[13px] font-semibold text-navy-900">{r.name}</span>
                  </span>
                  {r.pii && <Lock className="mt-0.5 size-3.5 shrink-0 text-ink-subtle" aria-label="Contains identifiable information" />}
                </button>
              </li>
            ))}
          </ul>
        </Card>

        <Panel
          title={def.name}
          subtitle={def.description}
          actions={
            output && canExport ? (
              <>
                <Button size="sm" variant="secondary" icon={<Download className="size-3.5" />} onClick={() => doExport('pdf')}>PDF</Button>
                <Button size="sm" variant="secondary" icon={<FileSpreadsheet className="size-3.5" />} onClick={() => doExport('xlsx')}>Excel</Button>
              </>
            ) : undefined
          }
        >
          {!dataset ? (
            <p className="text-[13px] text-ink-muted">
              No senior citizen masterlist is loaded in this browser. <Link to="/analytics" className="font-semibold text-info hover:underline">Load it in Analytics</Link>.
            </p>
          ) : locked ? (
            <p className="flex items-center gap-2 text-[13px] text-ink-muted"><Lock className="size-4" /> This report lists individual residents and needs access to resident records.</p>
          ) : output ? (
            <>
              <p className="mb-3 rounded-md bg-danger-tint px-3 py-2 text-[12px] font-semibold text-danger-ink">Internal analytics report: not an official government submission.</p>
              <label className="mb-3 flex items-center gap-2 text-[12.5px] text-navy-900">
                <input type="checkbox" className="size-4 accent-[#002132]" checked={useFilters} onChange={(e) => setUseFilters(e.target.checked)} />
                Apply the filters currently set in Analytics
              </label>
              <dl className="grid gap-x-6 gap-y-1 text-[12.5px] sm:grid-cols-2">
                {output.meta.map(([k, v]) => (
                  <div key={k} className="flex gap-2"><dt className="w-32 shrink-0 text-ink-muted">{k}</dt><dd className="min-w-0 break-words text-navy-900">{v}</dd></div>
                ))}
              </dl>
              {output.summary.length > 0 && (
                <table className="mt-4 w-full max-w-lg text-[13px]">
                  <tbody>
                    {output.summary.map(([k, v]) => (
                      <tr key={k} className="border-t border-line-soft"><td className="py-1.5 text-navy-900">{k}</td><td className="py-1.5 text-right font-semibold tabular-nums text-navy-900">{v}</td></tr>
                    ))}
                  </tbody>
                </table>
              )}
              {output.rows.length > 0 && (
                <div className="mt-4 max-h-[420px] overflow-auto rounded-md border border-line-soft">
                  <table className="w-full text-[12.5px]">
                    <thead className="sticky top-0 bg-surface-muted">
                      <tr className="text-left">{output.columns.map((c) => <th key={c} className="label-caps px-3 py-2">{c}</th>)}</tr>
                    </thead>
                    <tbody>
                      {output.rows.slice(0, 200).map((r, i) => (
                        <tr key={i} className="border-t border-line-soft">{r.map((v, j) => <td key={j} className="px-3 py-1.5 text-navy-900">{v}</td>)}</tr>
                      ))}
                    </tbody>
                  </table>
                  {output.rows.length > 200 && <p className="px-3 py-2 text-[12px] text-ink-muted">Preview shows 200 of {output.rows.length} rows. Exports include all rows.</p>}
                </div>
              )}
              {!canExport && <p className="mt-3 text-[12px] text-ink-muted">Your account can view but not export reports.</p>}
            </>
          ) : null}
        </Panel>
      </div>
    </>
  )
}
