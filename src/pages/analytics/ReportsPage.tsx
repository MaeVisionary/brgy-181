import { Download, FileSpreadsheet, Lock, Upload } from '@/icons'
import { Fragment, useEffect, useMemo, useRef, useState } from 'react'
import { Link } from 'react-router-dom'
import { useAuth } from '@/auth/useAuth'
import { useAnalytics } from '@/analytics/AnalyticsContext'
import { FILTER_LABELS, applyFilters, deriveRows, type Filters } from '@/analytics/compute'
import { exportExcel, exportPdf, type ReportOutput } from '@/analytics/exporters'
import { SENIOR_REPORTS } from '@/analytics/reports'
import { Button } from '@/components/ui/Button'
import { PageHeader } from '@/components/ui/PageHeader'
import { Card, Panel } from '@/components/ui/Panel'
import { BARANGAY } from '@/config/barangay'
import { cn } from '@/lib/cn'
import { formatShortDate } from '@/lib/format'
import { audit } from '@/services/auditService'
import { ServiceError } from '@/services/mockApi'
import { listReportTemplates, saveReportTemplate, type ReportTemplate } from '@/services/reportTemplateService'
import { downloadBlob } from '@/services/templateService'
import { ServiceReports } from './ServiceReports'
import { BUILTIN_REPORT_TEMPLATES, builtInTemplateUrl } from '@/config/reportTemplates'

export function ReportsPage() {
  const { user, can } = useAuth()
  const { dataset, reportingDate, filters } = useAnalytics()
  const [reportId, setReportId] = useState(SENIOR_REPORTS[1].id)
  const [useFilters, setUseFilters] = useState(false)
  const showPii = can('residents.view')
  const canExport = can('reports.export')
  const def = SENIOR_REPORTS.find((r) => r.id === reportId)!
  const locked = def.pii && !showPii

  const output = useMemo<ReportOutput | null>(() => {
    if (!dataset || locked) return null
    const rows = applyFilters(deriveRows(dataset, reportingDate), useFilters ? filters : ({} as Filters), { searchNames: showPii })
    const built = def.build(rows, { showPii })
    const active = Object.entries(useFilters ? filters : {}).filter(([, v]) => v)
    return {
      title: def.name,
      meta: [
        ['Barangay', BARANGAY.fullName],
        ['Source dataset', dataset.fileName],
        ['Reporting date', reportingDate.toISOString().slice(0, 10)],
        ['Date generated', new Date().toLocaleString('en-PH')],
        ['Generated by', `${user?.fullName ?? ''} (${user?.position ?? ''})`],
        ['Filters', active.map(([k, v]) => `${FILTER_LABELS[k as keyof Filters]}: ${v}`).join('; ') || 'None (all records)'],
      ],
      ...built,
    }
  }, [dataset, reportingDate, filters, useFilters, def, locked, showPii, user])

  useEffect(() => {
    if (output && user) audit(user, `Generated report: ${def.name}`, 'Reports')
    // log once per report selection, not on every render
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [reportId, dataset])

  // Official templates: the Secretary uploads, replaces or deletes them.
  const canManageTemplates = can('documents.process') || can('residents.import')
  const [templates, setTemplates] = useState<Record<string, ReportTemplate>>({})
  const [templateMsg, setTemplateMsg] = useState<{ ok: boolean; text: string } | null>(null)
  useEffect(() => {
    listReportTemplates().then(setTemplates)
  }, [])
  const upload = async (id: string, label: string, file: File) => {
    setTemplateMsg(null)
    try {
      await saveReportTemplate(id, label, file, user!)
      setTemplates(await listReportTemplates())
      setTemplateMsg({ ok: true, text: `${label}: "${file.name}" uploaded.` })
    } catch (e) {
      setTemplateMsg({ ok: false, text: e instanceof ServiceError ? e.message : 'The file could not be uploaded.' })
    }
  }

  const doExport = async (kind: 'pdf' | 'xlsx') => {
    if (!output || !user) return
    audit(user, `Exported ${kind.toUpperCase()}: ${def.name}`, 'Reports', def.pii ? 'contains identifiable information' : undefined)
    if (kind === 'pdf') exportPdf(output)
    else await exportExcel(output)
  }

  return (
    <>
      <PageHeader title="Barangay Reports" />

      {templateMsg && <p role="status" className={cn('mb-3 rounded-md px-3 py-2 text-[length:calc(14.5px*var(--fs))]', templateMsg.ok ? 'bg-success-tint text-navy-900' : 'bg-danger-tint text-danger-ink')}>{templateMsg.text}</p>}
      <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
        <Panel title="Official Forms" bodyClassName="px-0 py-0">
          <ul className="divide-y divide-line-soft">
            {OFFICIAL_FORMS.map((r) => (
              <ReportRow key={r.id} id={r.id} name={r.name} agency={r.agency} template={templates[r.id]} canManage={canManageTemplates} onUpload={upload} />
            ))}
          </ul>
        </Panel>
        <Panel title="Regular Reports" bodyClassName="px-0 py-0">
          <ul className="divide-y divide-line-soft">
            {REGULAR_REPORTS.map((r) => (
              <ReportRow key={r.id} id={r.id} name={r.name} agency={r.agency} template={templates[r.id]} canManage={canManageTemplates} onUpload={upload} />
            ))}
          </ul>
        </Panel>
      </div>

      <ServiceReports />

      <div className="mt-4 grid grid-cols-1 gap-4 xl:grid-cols-[240px_minmax(0,1fr)]">
        {/* Desktop: report list. Phones/tablets: a compact selector. */}
        <nav aria-label="Analytics reports" className="hidden h-fit xl:sticky xl:top-0 xl:block">
          <h2 className="label-caps mb-2 px-3">Analytics</h2>
          <ul className="space-y-0.5">
            {SENIOR_REPORTS.map((r) => (
              <li key={r.id}>
                <button type="button" onClick={() => setReportId(r.id)} aria-current={r.id === reportId ? 'page' : undefined} className={cn('flex w-full items-center gap-2 rounded-[var(--radius-control)] px-3 py-2 text-left text-[length:calc(15px*var(--fs))]', r.id === reportId ? 'bg-surface font-semibold text-navy-900 shadow-[0_0_0_1px_var(--color-line)]' : 'text-ink-nav hover:bg-surface/70 hover:text-navy-900')}>
                  <span className="min-w-0 flex-1 truncate">{SHORT_NAME[r.id] ?? r.name}</span>
                  {r.pii && <Lock className="size-3.5 shrink-0 text-ink-subtle" aria-label="Contains identifiable information" />}
                </button>
              </li>
            ))}
          </ul>
        </nav>

        <Card className="min-w-0 px-5 py-4">
          <label className="mb-3 block xl:hidden">
            <span className="sr-only">Report</span>
            <select value={reportId} onChange={(e) => setReportId(e.target.value)} className="h-11 w-full rounded-[var(--radius-control)] border border-line bg-surface px-3 text-[length:calc(15.5px*var(--fs))] font-semibold text-navy-900">
              {SENIOR_REPORTS.map((r) => <option key={r.id} value={r.id}>{SHORT_NAME[r.id] ?? r.name}</option>)}
            </select>
          </label>
          <div className="flex flex-wrap items-start justify-between gap-3">
            <div className="min-w-0">
              <h2 className="font-display text-[length:calc(20px*var(--fs))] font-bold text-navy-900">{def.name}</h2>
              {dataset && <p className="text-[length:calc(14px*var(--fs))] text-ink-muted">As of {formatShortDate(reportingDate.toISOString())}</p>}
            </div>
            {output && canExport && (
              <div className="flex gap-2">
                <Button size="sm" variant="secondary" icon={<Download className="size-3.5" />} onClick={() => doExport('pdf')}>PDF</Button>
                <Button size="sm" variant="secondary" icon={<FileSpreadsheet className="size-3.5" />} onClick={() => doExport('xlsx')}>Excel</Button>
              </div>
            )}
          </div>

          {!dataset ? (
            <p className="mt-3 text-[length:calc(15px*var(--fs))] text-ink-muted">
              No masterlist loaded. <Link to="/analytics" className="font-semibold text-info hover:underline">Load it in Analytics</Link>.
            </p>
          ) : locked ? (
            <p className="mt-3 flex items-center gap-2 text-[length:calc(15px*var(--fs))] text-ink-muted"><Lock className="size-4" /> Requires access to resident records.</p>
          ) : output ? (
            <>
              {output.summary.length > 0 && (
                <dl className="mt-4 grid grid-cols-2 gap-x-6 gap-y-4 sm:grid-cols-4">
                  {output.summary.slice(0, 4).map(([k, v]) => (
                    <div key={k} className="min-w-0">
                      <dd className="font-display text-[length:calc(26px*var(--fs))] leading-none font-extrabold tabular-nums text-navy-900">{v}</dd>
                      <dt className="mt-1 text-[length:calc(14px*var(--fs))] leading-snug text-ink-nav">{k}</dt>
                    </div>
                  ))}
                </dl>
              )}
              {output.summary.length > 4 && (
                <dl className="mt-4 grid grid-cols-1 gap-x-8 border-t border-line-soft pt-3 text-[length:calc(14.5px*var(--fs))] sm:grid-cols-2">
                  {output.summary.slice(4).map(([k, v]) => (
                    <div key={k} className="flex items-baseline justify-between gap-3 border-b border-line-soft py-1.5">
                      <dt className="text-ink-nav">{k}</dt>
                      <dd className="font-semibold tabular-nums text-navy-900">{v}</dd>
                    </div>
                  ))}
                </dl>
              )}
              {output.rows.length > 0 && (
                <ul className="mt-4 divide-y divide-line-soft border-y border-line-soft md:hidden">
                  {output.rows.slice(0, 50).map((r, i) => (
                    <li key={i} className="py-2.5">
                      <p className="text-[length:calc(15px*var(--fs))] font-semibold text-navy-900">{r[0]}</p>
                      <p className="text-[length:calc(13.5px*var(--fs))] text-ink-muted">{r.slice(1).map((v, j) => `${output.columns[j + 1]}: ${v}`).join(' · ')}</p>
                    </li>
                  ))}
                  {output.rows.length > 50 && <li className="py-2 text-[length:calc(14px*var(--fs))] text-ink-muted">Showing 50 of {output.rows.length}. Export to see all.</li>}
                </ul>
              )}
              {output.rows.length > 0 && (
                <div className="mt-4 hidden max-h-[420px] overflow-auto rounded-md border border-line-soft md:block">
                  <table className="w-full text-[length:calc(14.5px*var(--fs))]">
                    <thead className="sticky top-0 bg-surface-muted">
                      <tr className="text-left">{output.columns.map((c) => <th key={c} className="label-caps px-3 py-2 whitespace-nowrap">{c}</th>)}</tr>
                    </thead>
                    <tbody>
                      {output.rows.slice(0, 200).map((r, i) => (
                        <tr key={i} className="border-t border-line-soft">{r.map((v, j) => <td key={j} className="px-3 py-1.5 text-navy-900">{v}</td>)}</tr>
                      ))}
                    </tbody>
                  </table>
                  {output.rows.length > 200 && <p className="px-3 py-2 text-[length:calc(14px*var(--fs))] text-ink-muted">Showing 200 of {output.rows.length} rows.</p>}
                </div>
              )}
              <details className="mt-4 text-[length:calc(14px*var(--fs))]">
                <summary className="cursor-pointer font-semibold text-ink-nav hover:text-navy-900">Report details</summary>
                <label className="mt-2 flex items-center gap-2 text-navy-900">
                  <input type="checkbox" className="size-4 accent-[#002132]" checked={useFilters} onChange={(e) => setUseFilters(e.target.checked)} />
                  Use Analytics filters
                </label>
                <dl className="mt-2 grid grid-cols-[auto_1fr] gap-x-4 gap-y-1">
                  {output.meta.map(([k, v]) => (
                    <Fragment key={k}><dt className="text-ink-muted">{k}</dt><dd className="break-words text-navy-900">{v}</dd></Fragment>
                  ))}
                </dl>
              </details>
            </>
          ) : null}
        </Card>
      </div>
    </>
  )
}

const SHORT_NAME: Record<string, string> = {
  masterlist: 'Masterlist',
  summary: 'Population',
  age: 'Age Distribution',
  gender: 'Gender',
  address: 'Address',
  osca: 'OSCA Registration',
  status: 'Senior Citizen Status',
  bedridden: 'Bedridden Residents',
  quality: 'Data Quality',
}

const OFFICIAL_FORMS = [
  { id: 'dilg', name: 'BOIS Form', agency: 'DILG' },
  { id: 'osca', name: 'Senior Citizen Social Pension Transmittal', agency: 'OSCA' },
  { id: 'madao', name: 'BADAC Monthly Report Transmittal', agency: 'MADAO' },
  { id: 'bureau', name: 'Monthly Accomplishment Report', agency: 'Barangay Bureau' },
]
const REGULAR_REPORTS = [
  { id: 'recurring-cleanup', name: 'Clean-up Activities Report', agency: 'DILG' },
  { id: 'recurring-senior-masterlist', name: 'Senior Citizen Masterlist', agency: 'OSCA' },
  { id: 'recurring-kp', name: 'Katarungang Pambarangay Report', agency: 'Lupon' },
  { id: 'recurring-personnel', name: 'Barangay Personnel Report', agency: 'DILG' },
]

/** One report: name, agency, download (an uploaded file replaces the bundled one). */
function ReportRow({ id, name, agency, template, canManage, onUpload }: {
  id: string
  name: string
  agency: string
  template?: ReportTemplate
  canManage: boolean
  onUpload: (id: string, label: string, file: File) => void
}) {
  const input = useRef<HTMLInputElement>(null)
  const builtIn = BUILTIN_REPORT_TEMPLATES[id]
  const btn = 'inline-flex h-10 shrink-0 items-center justify-center gap-2 rounded-[var(--radius-control)] border border-line bg-surface w-10 sm:w-auto sm:px-3.5 text-[length:calc(14.5px*var(--fs))] font-semibold whitespace-nowrap text-navy-900 hover:bg-surface-muted'
  return (
    <li className="flex items-center gap-3 px-5 py-3">
      <span className="min-w-0 flex-1">
        <span className="block font-semibold text-navy-900">{name}</span>
        <span className="block text-[length:calc(14px*var(--fs))] text-ink-muted">{agency}</span>
      </span>
      {template ? (
        <button type="button" className={btn} aria-label={`Download ${name}`} onClick={() => downloadBlob(template.blob, template.fileName)}><Download className="size-4" /><span className="hidden sm:inline">Download</span></button>
      ) : builtIn ? (
        <a className={btn} href={builtInTemplateUrl(builtIn)} download={builtIn.fileName} aria-label={`Download ${name}`}><Download className="size-4" /><span className="hidden sm:inline">Download</span></a>
      ) : null}
      {canManage && (
        <>
          <input ref={input} type="file" accept=".pdf,.doc,.docx,.xls,.xlsx,.csv" className="sr-only" onChange={(e) => { const f = e.target.files?.[0]; if (f) onUpload(id, name, f); e.target.value = '' }} />
          <button type="button" onClick={() => input.current?.click()} aria-label={`Replace ${name} file`} title="Replace file" className="grid size-10 shrink-0 place-items-center rounded-[var(--radius-control)] text-ink-nav hover:bg-surface-muted hover:text-navy-900">
            <Upload className="size-4" />
          </button>
        </>
      )}
    </li>
  )
}
