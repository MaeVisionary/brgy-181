import { Download, FileSpreadsheet } from '@/icons'
import { useMemo, useState } from 'react'
import { useAuth } from '@/auth/useAuth'
import { exportExcel, exportPdf, type ReportOutput } from '@/analytics/exporters'
import { Button } from '@/components/ui/Button'
import { TextInput } from '@/components/ui/Field'
import { Card } from '@/components/ui/Panel'
import { BARANGAY } from '@/config/barangay'
import { ROLES } from '@/config/permissions'
import { getDocumentType } from '@/documents/catalog'
import { statusLabel } from '@/documents/workflows'
import { useAsync } from '@/hooks/useAsync'
import { useDocActor } from '@/hooks/useDocActor'
import { cn } from '@/lib/cn'
import { formatDate } from '@/lib/format'
import { mockUsers } from '@/mocks/users'
import { audit } from '@/services/auditService'
import { STAGE_LABEL, listCases } from '@/services/caseService'
import { listRequests } from '@/services/documentService'
import { equipmentStatus, listBorrowings, listEquipment, returnState } from '@/services/equipmentService'

type ReportId = 'documents' | 'complaints' | 'borrowing' | 'equipment' | 'personnel' | 'fees'

const REPORTS: { id: ReportId; name: string; description: string }[] = [
  { id: 'documents', name: 'Document requests', description: 'Requests by status and document type.' },
  { id: 'complaints', name: 'Complaints and mediation outcomes', description: 'Blotter entries, case stages and outcomes.' },
  { id: 'borrowing', name: 'Equipment borrowing', description: 'Borrowing requests, releases, returns and overdue items.' },
  { id: 'equipment', name: 'Equipment availability', description: 'Units available, reserved, borrowed and under maintenance.' },
  { id: 'personnel', name: 'Personnel processing activity', description: 'Workflow steps recorded by each official.' },
  { id: 'fees', name: 'Fees collected', description: 'Payments recorded by the Treasurer.' },
]

const inRange = (iso: string | undefined, from: string, to: string) => !!iso && (!from || iso.slice(0, 10) >= from) && (!to || iso.slice(0, 10) <= to)
const count = <T,>(items: T[], key: (t: T) => string) => {
  const m = new Map<string, number>()
  for (const t of items) m.set(key(t), (m.get(key(t)) ?? 0) + 1)
  return [...m.entries()].sort((a, b) => b[1] - a[1])
}
const userName = (id: string) => mockUsers.find((u) => u.id === id)?.fullName ?? 'Resident'

/** Reports built from the stored records (no fixed or sample totals). */
export function ServiceReports() {
  const { user, can } = useAuth()
  const actor = useDocActor()!
  const docs = useAsync(() => listRequests(actor), [actor]).data
  const cases = useAsync(() => listCases(actor, { includeRemoved: true }), [actor]).data
  const borrowings = useAsync(() => listBorrowings(actor), [actor]).data
  const equipment = useAsync(listEquipment, []).data
  const [id, setId] = useState<ReportId>('documents')
  const [from, setFrom] = useState('')
  const [to, setTo] = useState('')
  const def = REPORTS.find((r) => r.id === id)!

  const output = useMemo<ReportOutput | null>(() => {
    if (!docs || !cases || !borrowings || !equipment) return null
    const meta: [string, string][] = [
      ['Barangay', BARANGAY.fullName],
      ['Period', from || to ? `${from ? formatDate(from) : 'Start'} to ${to ? formatDate(to) : 'today'}` : 'All dates'],
      ['Generated', new Date().toLocaleString('en-PH')],
      ['Generated by', `${user?.fullName ?? ''} (${user?.position ?? ''})`],
    ]
    if (id === 'documents') {
      const list = docs.filter((d) => getDocumentType(d.typeId).category !== 'case' && inRange(d.submittedAt, from, to))
      const pending = ['submitted', 'under_review', 'needs_info', 'processing', 'pending_approval', 'for_assessment']
      return {
        title: 'Document requests report',
        meta,
        summary: [
          ['Total requests', list.length],
          ['Pending', list.filter((d) => pending.includes(d.status)).length],
          ['Approved (printing to pickup)', list.filter((d) => ['approved', 'for_signature', 'ready_for_pickup'].includes(d.status)).length],
          ['Completed', list.filter((d) => d.status === 'released').length],
          ['Rejected', list.filter((d) => d.status === 'rejected').length],
          ['Cancelled', list.filter((d) => d.status === 'cancelled').length],
        ],
        columns: ['Reference no.', 'Document', 'Requester', 'Submitted', 'Status'],
        rows: list.map((d) => [d.referenceNo, getDocumentType(d.typeId).name, d.requesterName, formatDate(d.submittedAt), statusLabel(d.status, getDocumentType(d.typeId).workflow)]),
      }
    }
    if (id === 'complaints') {
      const list = cases.filter((c) => inRange(c.filedAt, from, to))
      return {
        title: 'Complaints and mediation outcomes',
        meta,
        summary: [
          ['Blotter entries / cases', list.length],
          ['Open', list.filter((c) => !['settled', 'closed'].includes(c.stage)).length],
          ['Settled', list.filter((c) => c.outcome?.type === 'settled').length],
          ['Not settled (certificate to file action)', list.filter((c) => c.outcome?.type === 'not_settled').length],
          ['Dismissed or withdrawn', list.filter((c) => c.outcome && ['dismissed', 'withdrawn'].includes(c.outcome.type)).length],
          ['Hearings held', list.flatMap((c) => c.hearings).filter((h) => h.status === 'held').length],
        ],
        columns: ['Case no.', 'Blotter no.', 'Nature', 'Filed', 'Stage', 'Outcome'],
        rows: list.map((c) => [c.caseNo, c.blotterNo ?? '', c.nature, formatDate(c.filedAt), STAGE_LABEL[c.stage], c.outcome ? c.outcome.type.replace('_', ' ') : '']),
      }
    }
    if (id === 'borrowing') {
      const list = borrowings.filter((b) => inRange(b.requestedAt, from, to))
      return {
        title: 'Equipment borrowing report',
        meta,
        summary: [
          ['Requests', list.length],
          ['Pending', list.filter((b) => b.status === 'pending').length],
          ['Reserved (approved)', list.filter((b) => b.status === 'approved').length],
          ['Borrowed now', list.filter((b) => b.status === 'released').length],
          ['Overdue', list.filter((b) => returnState(b) === 'overdue').length],
          ['Returned', list.filter((b) => b.status === 'returned').length],
        ],
        columns: ['Ref. no.', 'Borrower', 'Items', 'Requested', 'Status', 'Returned'],
        rows: list.map((b) => [
          b.refNo,
          b.borrowerName,
          b.items.map((i) => `${i.qty} ${equipment.find((e) => e.id === i.equipmentId)?.name ?? ''}`).join(', '),
          formatDate(b.requestedAt),
          returnState(b) === 'overdue' ? 'Overdue' : b.status,
          b.returnedAt ? formatDate(b.returnedAt) : '',
        ]),
      }
    }
    if (id === 'equipment') {
      const st = equipment.map((e) => ({ e, s: equipmentStatus(e) }))
      const sum = (k: keyof ReturnType<typeof equipmentStatus>) => st.reduce((n, x) => n + x.s[k], 0)
      return {
        title: 'Equipment availability report',
        meta: meta.filter(([k]) => k !== 'Period'),
        summary: [
          ['Total units', equipment.reduce((n, e) => n + e.totalQty, 0)],
          ['Available', sum('available')],
          ['Reserved', sum('reserved')],
          ['Borrowed', sum('borrowed')],
          ['Under maintenance', sum('maintenance')],
          ['Damaged or missing', equipment.reduce((n, e) => n + e.damagedQty + e.missingQty, 0)],
        ],
        columns: ['Equipment ID', 'Equipment', 'Location', 'Total', 'Available', 'Reserved', 'Borrowed', 'Maintenance', 'Damaged', 'Missing'],
        rows: st.map(({ e, s }) => [e.refNo, e.name, e.location ?? '', e.totalQty, s.available, s.reserved, s.borrowed, s.maintenance, e.damagedQty, e.missingQty]),
      }
    }
    if (id === 'personnel') {
      const steps = [
        ...docs.flatMap((d) => d.history.filter((h) => h.byRole !== 'resident').map((h) => ({ by: h.byUserId, role: h.byRole, at: h.at, area: 'Documents' }))),
        ...cases.flatMap((c) => c.history.filter((h) => h.byRole !== 'resident').map((h) => ({ by: h.byUserId, role: h.byRole, at: h.at, area: 'Cases' }))),
        ...borrowings.flatMap((b) => b.history.filter((h) => h.byRole !== 'resident').map((h) => ({ by: h.byUserId, role: h.byRole, at: h.at, area: 'Equipment' }))),
      ].filter((x) => inRange(x.at, from, to))
      const people = count(steps, (x) => x.by)
      return {
        title: 'Personnel processing activity',
        meta,
        summary: [
          ['Steps recorded', steps.length],
          ['Personnel involved', people.length],
          ['Document steps', steps.filter((x) => x.area === 'Documents').length],
          ['Case steps', steps.filter((x) => x.area === 'Cases').length],
          ['Equipment steps', steps.filter((x) => x.area === 'Equipment').length],
        ],
        columns: ['Personnel', 'Role', 'Documents', 'Cases', 'Equipment', 'Total'],
        rows: people.map(([uid, n]) => {
          const mine = steps.filter((x) => x.by === uid)
          return [userName(uid), ROLES[mine[0].role].name, mine.filter((x) => x.area === 'Documents').length, mine.filter((x) => x.area === 'Cases').length, mine.filter((x) => x.area === 'Equipment').length, n]
        }),
      }
    }
    const paid = docs.filter((d) => d.payment && inRange(d.payment.at, from, to))
    return {
      title: 'Fees collected',
      meta,
      summary: [
        ['Payments recorded', paid.length],
        ['Total amount (₱)', paid.reduce((n, d) => n + d.payment!.amount, 0).toFixed(2)],
        ['Unpaid requests with a fee', docs.filter((d) => getDocumentType(d.typeId).fee && !d.payment && !['rejected', 'cancelled'].includes(d.status)).length],
      ],
      columns: ['O.R. no.', 'Date', 'Document', 'Payor', 'Amount (₱)', 'Recorded by'],
      rows: paid.map((d) => [d.payment!.orNo, formatDate(d.payment!.at), getDocumentType(d.typeId).name, d.requesterName, d.payment!.amount.toFixed(2), userName(d.payment!.byUserId)]),
    }
  }, [id, from, to, docs, cases, borrowings, equipment, user])

  const doExport = async (kind: 'pdf' | 'xlsx') => {
    if (!output || !user) return
    audit(user, `Exported ${kind.toUpperCase()}: ${output.title}`, 'Reports')
    if (kind === 'pdf') exportPdf(output)
    else await exportExcel(output)
  }

  return (
    <div className="mt-4 grid grid-cols-1 gap-4 xl:grid-cols-[240px_minmax(0,1fr)]">
      <nav aria-label="Service reports" className="hidden h-fit xl:sticky xl:top-0 xl:block">
        <h2 className="label-caps mb-2 px-3">Services</h2>
        <ul className="space-y-0.5">
          {REPORTS.map((r) => (
            <li key={r.id}>
              <button type="button" onClick={() => setId(r.id)} aria-current={r.id === id ? 'page' : undefined} className={cn('w-full truncate rounded-[var(--radius-control)] px-3 py-2 text-left text-[length:calc(15px*var(--fs))]', r.id === id ? 'bg-surface font-semibold text-navy-900 shadow-[0_0_0_1px_var(--color-line)]' : 'text-ink-nav hover:bg-surface/70 hover:text-navy-900')}>
                {r.name}
              </button>
            </li>
          ))}
        </ul>
      </nav>
      <Card className="min-w-0 px-5 py-4">
        <label className="mb-3 block xl:hidden">
          <span className="sr-only">Service report</span>
          <select value={id} onChange={(e) => setId(e.target.value as typeof id)} className="h-11 w-full rounded-[var(--radius-control)] border border-line bg-surface px-3 text-[length:calc(15.5px*var(--fs))] font-semibold text-navy-900">
            {REPORTS.map((r) => <option key={r.id} value={r.id}>{r.name}</option>)}
          </select>
        </label>
        <div className="flex flex-wrap items-start justify-between gap-3">
          <h2 className="min-w-0 font-display text-[length:calc(20px*var(--fs))] font-bold text-navy-900">{def.name}</h2>
          {output && can('reports.export') && (
            <div className="flex gap-2">
              <Button size="sm" variant="secondary" icon={<Download className="size-3.5" />} onClick={() => doExport('pdf')}>PDF</Button>
              <Button size="sm" variant="secondary" icon={<FileSpreadsheet className="size-3.5" />} onClick={() => doExport('xlsx')}>Excel</Button>
            </div>
          )}
        </div>
        {id !== 'equipment' && (
          <div className="mt-3 grid grid-cols-2 items-end gap-3 sm:flex sm:flex-wrap">
            <label className="block min-w-0 text-[length:calc(14px*var(--fs))] font-semibold text-ink-nav">From<TextInput className="mt-0.5 w-full sm:w-44" type="date" value={from} max={to || undefined} onChange={(e) => setFrom(e.target.value)} /></label>
            <label className="block min-w-0 text-[length:calc(14px*var(--fs))] font-semibold text-ink-nav">To<TextInput className="mt-0.5 w-full sm:w-44" type="date" value={to} min={from || undefined} onChange={(e) => setTo(e.target.value)} /></label>
            {(from || to) && <Button size="sm" variant="ghost" onClick={() => { setFrom(''); setTo('') }}>Clear dates</Button>}
          </div>
        )}
        {!output ? (
          <div className="mt-4 h-40 animate-pulse rounded bg-surface-muted" />
        ) : (
          <>
            <dl className="mt-4 grid grid-cols-2 gap-x-6 gap-y-4 sm:grid-cols-4">
              {output.summary.slice(0, 4).map(([k, v]) => (
                <div key={k} className="min-w-0">
                  <dd className="font-display text-[length:calc(26px*var(--fs))] leading-none font-extrabold tabular-nums text-navy-900">{v}</dd>
                  <dt className="mt-1 text-[length:calc(14px*var(--fs))] leading-snug text-ink-nav">{k}</dt>
                </div>
              ))}
            </dl>
            {output.summary.length > 4 && (
              <dl className="mt-4 grid grid-cols-1 gap-x-8 border-t border-line-soft pt-3 text-[length:calc(14.5px*var(--fs))] sm:grid-cols-2">
                {output.summary.slice(4).map(([k, v]) => (
                  <div key={k} className="flex items-baseline justify-between gap-3 border-b border-line-soft py-1.5">
                    <dt className="text-ink-nav">{k}</dt>
                    <dd className="font-semibold tabular-nums text-navy-900">{v}</dd>
                  </div>
                ))}
              </dl>
            )}
            {output.rows.length === 0 ? (
              <p className="mt-4 text-[length:calc(15px*var(--fs))] text-ink-muted">No records for this period.</p>
            ) : (
              <>
              <ul className="mt-4 divide-y divide-line-soft border-y border-line-soft md:hidden">
                {output.rows.slice(0, 50).map((r, i) => (
                  <li key={i} className="py-2.5">
                    <p className="text-[length:calc(15px*var(--fs))] font-semibold text-navy-900">{r[0]}</p>
                    <p className="text-[length:calc(13.5px*var(--fs))] text-ink-muted">{r.slice(1).map((v, j) => `${output.columns[j + 1]}: ${v}`).join(' · ')}</p>
                  </li>
                ))}
              </ul>
              <div className="mt-4 hidden overflow-x-auto rounded-md border border-line-soft md:block">
                <table className="w-full min-w-[640px] text-[length:calc(14.5px*var(--fs))]">
                  <thead><tr className="bg-surface-muted text-left">{output.columns.map((c) => <th key={c} className="label-caps px-3 py-2 whitespace-nowrap">{c}</th>)}</tr></thead>
                  <tbody>
                    {output.rows.slice(0, 50).map((r, i) => (
                      <tr key={i} className="border-t border-line-soft">{r.map((v, j) => <td key={j} className="px-3 py-2 text-navy-900">{v}</td>)}</tr>
                    ))}
                  </tbody>
                </table>
              </div>
              </>
            )}
            {output.rows.length > 50 && <p className="mt-2 text-[length:calc(14px*var(--fs))] text-ink-muted">Showing 50 of {output.rows.length} rows. Export to see all.</p>}
            {output.note && <p className="mt-2 text-[length:calc(14px*var(--fs))] text-ink-muted">{output.note}</p>}
          </>
        )}
      </Card>
    </div>
  )
}
